# program to demonstrate operator precedence and associativity exercise

a = float(input("Enter a number : 1 : "))

b = float(input("Enter a number : 2 : "))

c = float(input("Enter a number : 3 : "))

d = float(input("Enter a number : 4 : "))

result = a + b * c ** d

print("result of", a, "+", b, "*", c, "**", d, "is :", result)
