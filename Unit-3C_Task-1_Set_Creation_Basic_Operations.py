# program to demonstrate set creation and basic set operations (union, intersection, difference)

set_a = {1, 2, 3, 4}
set_b = { 5, 6, 7, 8}

print("Set A:", set_a)
print("Set B:", set_b)
print("Union:", set_a | set_b)
print("Intersection:", set_a & set_b)
print("Difference (A - B):", set_a - set_b)